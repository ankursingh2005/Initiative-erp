const fs=require('fs');
const vm=require('vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync('static/ageing_stock.html','utf8');
for(const m of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)) new Function(m[1]);
const start=html.indexOf('    function scopedItem(');
const end=html.indexOf('    // "Present At"',start);
const ages=['age_0_60','age_61_90','age_91_150','age_151_180','age_181_365','age_366_plus'];
const context={AGE_COLS:ages.map(k=>[k,k]),selected:['qty_alm','qty_hzt'],durations:['age_366_plus']};
context.activeAgeCols=()=>context.durations.map(k=>[k,k]);
context.activeLocCols=()=>context.selected.map(k=>[k,k]);
vm.createContext(context);
vm.runInContext(html.slice(start,end),context);
const item={closing_qty:17,age_366_plus:17,qty_alm:3,qty_hzt:2,location_age_buckets_json:JSON.stringify({qty_alm:{age_366_plus:3,age_0_60:1},qty_hzt:{age_366_plus:2}})};
let scoped=context.scopedItem(item);
assert.equal(scoped.age_366_plus,5);
assert.equal(context.itemQtyInActiveDurations(scoped),5);
assert.equal(context.locationQtyForDurations(item,'qty_alm'),3);
context.selected=['qty_hzt'];
assert.equal(context.itemQtyInActiveDurations(context.scopedItem(item)),2);
context.selected=['qty_rbl'];
assert.equal(context.itemQtyInActiveDurations(context.scopedItem(item)),0);
assert.equal(context.locationQtyForDurations({qty_alm:9},'qty_alm'),0);
context.selected=['qty_alm','qty_hzt']; context.durations=ages;
assert.equal(context.itemQtyInActiveDurations(context.scopedItem(item)),6);
assert.equal(context.locationQtyForDurations(item,'qty_alm'),4);
console.log('Passed: script syntax, branch totals, duration totals, branch selection, missing stock, and all-duration reconciliation.');
