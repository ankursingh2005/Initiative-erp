// Run tests/ems_salary_preview.py and isolated headless Chrome on port 9246 first.
const assert=require('node:assert/strict'),fs=require('node:fs');
(async()=>{
 const target=(await(await fetch('http://127.0.0.1:9246/json')).json()).find(t=>t.type==='page');
 const ws=new WebSocket(target.webSocketDebuggerUrl);await new Promise(r=>ws.addEventListener('open',r,{once:true}));
 let id=0;const pending=new Map(),errors=[];
 ws.onmessage=e=>{const m=JSON.parse(e.data);if(m.method==='Runtime.exceptionThrown')errors.push(m.params);if(pending.has(m.id)){const p=pending.get(m.id);pending.delete(m.id);m.error?p.reject(Error(JSON.stringify(m.error))):p.resolve(m.result);}};
 const call=(method,params={})=>new Promise((resolve,reject)=>{const n=++id;pending.set(n,{resolve,reject});ws.send(JSON.stringify({id:n,method,params}));});
 const evaluate=async expression=>{const r=await call('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw Error(JSON.stringify(r.exceptionDetails));return r.result.value;};
 const wait=async expression=>{for(let n=0;n<100;n++){if(await evaluate(expression))return;await new Promise(r=>setTimeout(r,100));}throw Error('Timeout: '+expression);};
 const click=selector=>evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`);
 await call('Runtime.enable');await call('Page.enable');
 await call('Page.addScriptToEvaluateOnNewDocument',{source:"localStorage.setItem('token','isolated-test');localStorage.setItem('role','Admin');"});
 await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1050,deviceScaleFactor:1,mobile:false});
 await call('Page.navigate',{url:'http://127.0.0.1:8016/erp/ems'});
 await wait("document.getElementById('employeeCount')?.textContent==='5'");
 await evaluate("document.getElementById('month').value='2026-09';refresh()");
 await wait("document.getElementById('periodNote').textContent.startsWith('Closed month')");
 assert.equal(await evaluate("document.getElementById('homeLink').getAttribute('href')"),'/erp/home');
 assert.equal(await evaluate("document.getElementById('monthlyRows').textContent.includes('BrandPartner')"),false);
 await evaluate("document.getElementById('group').value='ac_projects';render()");
 assert.equal(await evaluate("document.getElementById('employeeCount').textContent"),'1');
 await evaluate("document.getElementById('group').value='';render()");
 fs.mkdirSync('tmp/ems-qa',{recursive:true});
 fs.writeFileSync('tmp/ems-qa/desktop.png',Buffer.from((await call('Page.captureScreenshot',{format:'png',captureBeyondViewport:true})).data,'base64'));
 await click('[data-review="3"]');
 assert.equal(await evaluate("document.getElementById('detail').open"),true);
 assert.equal(await evaluate("document.querySelectorAll('.day').length"),30);
 await evaluate("document.getElementById('ack').checked=true");await click('#publish');
 await wait("!document.getElementById('detail').open && document.getElementById('publishedCount').textContent==='1'");
 await click('[data-tab="records"]');await click('[data-slip]');
 await wait("document.getElementById('detail').open && document.getElementById('detailTitle').textContent.includes('Salary Slip')");
 assert.equal(await evaluate("document.getElementById('printSlip').hidden"),false);
 fs.writeFileSync('tmp/ems-qa/payslip.png',Buffer.from((await call('Page.captureScreenshot',{format:'png'})).data,'base64'));
 await click('#detailClose');
 await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
 await click('[data-tab="setup"]');
 assert.equal(await evaluate('document.documentElement.scrollWidth<=innerWidth'),true);
 fs.writeFileSync('tmp/ems-qa/mobile.png',Buffer.from((await call('Page.captureScreenshot',{format:'png',captureBeyondViewport:true})).data,'base64'));
 assert.equal(errors.length,0,JSON.stringify(errors));
 console.log('EMS UI passed: group filters, attendance review, salary publication, frozen payslip, mobile layout, ERP prefix.');
 ws.close();
})().catch(e=>{console.error(e);process.exit(1);});
